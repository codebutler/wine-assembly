'use strict';
const fs = require('fs'), os = require('os'), path = require('path');
const assert = require('assert/strict'), crypto = require('crypto');
const { prepare } = require('../tools/prepare-arena-gog-assets');
const sha = b => crypto.createHash('sha256').update(b).digest('hex');
const canonical = require('../lib/arena-gog-source.json');
assert.deepEqual(canonical.files, require('./candidate-corpus/gog-free-elder-scrolls-arena-files.json').files.map(f => ({path:f.path,bytes:f.size,sha256:f.sha256})));
assert(canonical.files.some(f => f.path === '__support/save/NAMES.DAT'));
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'arena-migration-'));
try {
  const put = (p, b) => { fs.mkdirSync(path.dirname(path.join(root,p)),{recursive:true}); fs.writeFileSync(path.join(root,p),b); return {path:p,bytes:Buffer.byteLength(b),sha256:sha(b)}; };
  const installer = put('game/setup.exe','installer');
  const payload = put('game/installed/ACD.EXE','original');
  const config = put('config.conf',fs.readFileSync(path.join(__dirname,'configs/arena-browser-wine-assembly.conf')));
  const old = Buffer.from('{"old":"known generated metadata"}\n');
  config.previousManifestSha256s = [sha(old)];
  const source = {installer,installedRoot:'game/installed',files:[{...payload,path:'ACD.EXE'}],config};
  put('game/.wine-assembly-browser.json',old);
  put('game/installed/cloud_saves/SAVEGAME.00','player save');
  put('game/installed/AUTOMAP.00','old local state');
  const result = prepare(root,source);
  assert.equal(result.originalFiles,1);
  assert.deepEqual(fs.readFileSync(path.join(root,'game/.wine-assembly-browser.json.before-'+sha(old))),old);
  assert.equal(fs.readFileSync(path.join(root,'game/installed/cloud_saves/SAVEGAME.00'),'utf8'),'player save');
  assert.equal(fs.readFileSync(path.join(root,'game/installed/AUTOMAP.00'),'utf8'),'old local state');
  assert.deepEqual(prepare(root,source),result);
  const conf = fs.readFileSync(path.join(root,'game/arena-wa.conf'));
  put('game/.wine-assembly-browser.json','unknown player metadata');
  assert.throws(() => prepare(root,source),/Existing metadata conflict/);
  assert.equal(fs.readFileSync(path.join(root,'game/.wine-assembly-browser.json'),'utf8'),'unknown player metadata');
  assert.deepEqual(fs.readFileSync(path.join(root,'game/arena-wa.conf')),conf);
  console.log('PASS canonical Arena inventory, known migration backup, idempotence, save/state preservation and unknown-metadata refusal');
} finally { fs.rmSync(root,{recursive:true,force:true}); }
