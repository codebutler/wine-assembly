#!/usr/bin/env node
'use strict';

// Write lib/app-file-sizes.generated.js: the byte size of every inline
// `files[]` entry of every app in lib/apps.js, keyed by the URL exactly as the
// registry writes it.
//
//   node tools/gen-app-file-sizes.js            # regenerate
//   node tools/gen-app-file-sizes.js --check    # fail if a present file is stale
//   ... --data-root=PATH   resolve file URLs under another checkout (one with
//                          the full gitignored corpus) instead of this one
//
// Why: the lazy-file default (lib/app-files.js) streams a large data file only
// when it knows the file's size -- an unsized file stays eager, because the
// policy cannot tell a 4 KB licence text that a non-parking reader opens from
// a 60 MB archive (AoE II's EULA.RTF, 8bcc3055). Local media manifests carry
// sizes; the hand-written inline entries did not, so after 8bcc3055 every one
// of them loaded up front again. lib/apps.js stamps these sizes onto its inline
// entries, so both hosts see the same sized registry and decide identically.
//
// A size is only an input to the eager/lazy decision. Streamed entries are
// httpRange, which learns the real length from the server, so a stale size can
// misplace a file between the two piles but cannot corrupt a read.
//
// Only files of at least SMALL_FILE_BYTES are recorded (all files once the
// policy has no such rule, i.e. the constant is gone): an unsized file stays
// eager anyway, and so does a small one, so a smaller size changes no decision
// and would only make every page load a bigger script. (The one rule that
// wants every size, "whole app under APP_EAGER_BYTES -> all eager", then
// applies only to apps with no large file at all -- which is what it is for.)
//
// Files absent from this checkout (sparse worktrees, gitignored corpus) keep
// their recorded size; --check therefore fails only on a file that is present
// and recorded wrong, or present and not recorded at all.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const policy = require(path.join(ROOT, 'lib', 'app-files.js'));
// No small-file rule in the policy => every size can change a decision.
const RECORD_FROM = Number.isSafeInteger(policy.SMALL_FILE_BYTES) ? policy.SMALL_FILE_BYTES : 0;
const OUTPUT = path.join(ROOT, 'lib', 'app-file-sizes.generated.js');
const CHECK = process.argv.includes('--check');
const rootArg = process.argv.find(a => a.startsWith('--data-root='));
const DATA_ROOT = rootArg ? path.resolve(rootArg.slice('--data-root='.length)) : ROOT;

function loadRecorded() {
  try {
    delete require.cache[require.resolve(OUTPUT)];
    return require(OUTPUT) || {};
  } catch (_) { return {}; }
}

function inlineUrls() {
  // The registry before sizes are stamped: read the raw entries.
  process.env.WA_APP_FILE_SIZES_OFF = '1';
  delete require.cache[require.resolve(path.join(ROOT, 'lib', 'apps.js'))];
  const { APPS } = require(path.join(ROOT, 'lib', 'apps.js'));
  delete process.env.WA_APP_FILE_SIZES_OFF;
  const urls = new Set();
  for (const app of Object.values(APPS)) {
    for (const item of app.files || []) {
      const url = typeof item === 'string' ? item : item && item.url;
      if (url && !/^[a-z]+:/i.test(url)) urls.add(url);
    }
  }
  return [...urls].sort();
}

function sizeOnDisk(url) {
  try {
    const st = fs.statSync(path.isAbsolute(url) ? url : path.join(DATA_ROOT, url));
    return st.isFile() ? st.size : null;
  } catch (_) { return null; }
}

function render(sizes) {
  const lines = Object.keys(sizes).sort().map(url => `    ${JSON.stringify(url)}: ${sizes[url]},`);
  return [
    '// Generated by tools/gen-app-file-sizes.js; do not edit. Byte sizes of the',
    '// inline files[] entries in lib/apps.js, which stamps them onto its entries',
    '// so the lazy-file policy (lib/app-files.js) can stream the large ones.',
    '(function () {',
    '  const sizes = {',
    ...lines,
    '  };',
    '  if (typeof module !== "undefined" && module.exports) module.exports = sizes;',
    '  if (typeof window !== "undefined") window.wineAppFileSizes = sizes;',
    '})();',
    '',
  ].join('\n');
}

const recorded = loadRecorded();
const urls = inlineUrls();
const next = {};
const stale = [], missing = [];
for (const url of urls) {
  const size = sizeOnDisk(url);
  if (size === null) {
    if (Number.isSafeInteger(recorded[url])) next[url] = recorded[url];
    else missing.push(url);
    continue;
  }
  if (size < RECORD_FROM) {
    if (recorded[url] !== undefined) stale.push(`${url}: recorded ${recorded[url]}, now below the threshold`);
    continue;
  }
  next[url] = size;
  if (recorded[url] !== size) stale.push(`${url}: recorded ${recorded[url]}, on disk ${size}`);
}

if (CHECK) {
  if (stale.length) {
    console.error(`app file sizes are stale for ${stale.length} file(s); run node tools/gen-app-file-sizes.js`);
    for (const line of stale.slice(0, 20)) console.error(`  ${line}`);
    process.exit(1);
  }
  console.log(`app file sizes: OK (${Object.keys(next).length} recorded, ${missing.length} absent and unrecorded)`);
} else {
  fs.writeFileSync(OUTPUT, render(next));
  console.log(`Wrote ${path.relative(ROOT, OUTPUT)}: ${Object.keys(next).length} sizes ` +
    `(${stale.length} changed, ${missing.length} absent here and unrecorded)`);
}
